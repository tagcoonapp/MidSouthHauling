// Bundles the built web app (dist/) into the Worker as a generated module, so a deploy is a single
// script upload. (Cloud sessions can't use Wrangler's separate static-asset upload; see README.)
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, extname } from "node:path";

const DIST = "dist";
const OUT = "worker/static-assets.generated.ts";
const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
  ".webmanifest": "application/manifest+json",
  ".json": "application/json",
  ".png": "image/png",
  ".ico": "image/x-icon",
  ".txt": "text/plain; charset=utf-8",
};
const TEXT = new Set([".html", ".js", ".css", ".svg", ".webmanifest", ".json", ".txt"]);

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const entries = walk(DIST).map((p) => {
  const ext = extname(p);
  const type = TYPES[ext];
  if (!type) throw new Error(`Unknown file type in dist: ${p}`);
  const isText = TEXT.has(ext);
  const body = isText ? readFileSync(p, "utf8") : readFileSync(p).toString("base64");
  return [`/${relative(DIST, p).split("\\").join("/")}`, { type, body, base64: !isText }];
});

writeFileSync(
  OUT,
  `// GENERATED by scripts/embed-assets.mjs from dist/. Do not edit.\n` +
    `export const STATIC_ASSETS: Record<string, { type: string; body: string; base64: boolean }> = ${JSON.stringify(Object.fromEntries(entries))};\n`,
);
console.log(`Embedded ${entries.length} files into ${OUT}`);
